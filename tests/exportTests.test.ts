import { describe, it, expect } from 'vitest';
import ts from 'typescript';
import { exportVitest } from '../src/core/exportTests';
import type { Args, Label, LabeledDivergence, Outcome } from '../src/core/types';

function item(label: Label, old: Outcome, next: Outcome, args: Args = ['00128']): LabeledDivergence {
  return { label, divergence: { args, pair: { old, new: next }, reasons: [], originalArgs: [], shrinkSteps: 0 } };
}
function render(items: LabeledDivergence[]) {
  const code = exportVitest({ fnName: 'normalizeOrderId', importPath: './new', items });
  const result = ts.transpileModule(code, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } });
  expect(result.diagnostics).toEqual([]);
  return code;
}
const returned = (value: unknown): Outcome => ({ kind: 'return', value });

describe('exportVitest', () => {
  it('exports bug return tests against the old outcome', () => {
    const code = render([item('bug', returned('00128'), returned('128'))]);
    expect(code).toContain('// Generated by DiffWitness. Labels: bug = new must match old; intended = new behavior pinned.');
    expect(code).toContain("import { describe, it, expect } from 'vitest';");
    expect(code).toContain("import { normalizeOrderId } from './new';");
    expect(code).toContain("describe('normalizeOrderId (DiffWitness)'");
    expect(code).toContain(String.raw`it("bug: normalizeOrderId(\"00128\")", () => {`);
    expect(code).toContain('expect(normalizeOrderId("00128")).toEqual("00128");');
  });
  it('pins intended throws to the new outcome and escapes error names', () => {
    const code = render([item('intended', returned(1), { kind: 'throw', name: 'TypeError\nunsafe', message: 'bad' })]);
    expect(code).toContain('intended: normalizeOrderId');
    expect(code).toContain('expect(() => normalizeOrderId("00128")).toThrow(); // "TypeError\\nunsafe"');
  });
  it('skips selected timeouts', () => {
    const code = render([item('bug', { kind: 'timeout' }, returned(1))]);
    expect(code).toContain('it.skip(');
    expect(code).toContain('// timed out');
  });
  it('preserves numeric and nested literals', () => {
    const code = render([item('intended', returned(null), returned({ nested: [-0, NaN, Infinity, -Infinity, undefined, null, true], 'odd key': 'a\n"b' }))]);
    expect(code).toContain('nested: [-0, NaN, Infinity, -Infinity, undefined, null, true]');
    expect(code).toContain('"odd key": "a\\n\\"b"');
  });
  it('emits Date, Map, Set and unsupported values', () => {
    const code = render([item('bug', returned([new Date('2026-01-01T00:00:00.000Z'), new Map([['x', 1]]), new Set([2]), /x/]), returned(null))]);
    expect(code).toContain('new Date("2026-01-01T00:00:00.000Z")');
    expect(code).toContain('new Map([["x", 1]])');
    expect(code).toContain('new Set([2])');
    expect(code).toContain('/* unsupported */ undefined');
  });
  it('handles empty items with one todo', () => {
    const code = render([]);
    expect(code).toContain("it.todo('no labeled divergences');");
    expect(code.match(/it\.todo/g)).toHaveLength(1);
  });
});
