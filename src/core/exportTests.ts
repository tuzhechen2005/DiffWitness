import type { LabeledDivergence } from './types';

function quote(value: string): string {
  return `'${JSON.stringify(value).slice(1, -1).replace(/'/g, "\\'")}'`;
}

function literal(value: unknown, ancestors = new Set<object>()): string {
  if (value === undefined) return 'undefined';
  if (value === null) return 'null';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'boolean') return String(value);
  if (typeof value === 'number') return Object.is(value, -0) ? '-0' : String(value);
  if (typeof value !== 'object' || ancestors.has(value)) return '/* unsupported */ undefined';
  const nested = new Set(ancestors).add(value);
  const emit = (item: unknown) => literal(item, nested);
  if (value instanceof Date) {
    return Number.isNaN(value.getTime()) ? '/* unsupported */ undefined' : `new Date(${JSON.stringify(value.toISOString())})`;
  }
  if (Array.isArray(value)) return `[${Array.from(value, emit).join(', ')}]`;
  if (value instanceof Map) return `new Map([${Array.from(value, ([key, item]) => `[${emit(key)}, ${emit(item)}]`).join(', ')}])`;
  if (value instanceof Set) return `new Set([${Array.from(value, emit).join(', ')}])`;
  if (Object.getPrototypeOf(value) === Object.prototype || Object.getPrototypeOf(value) === null) {
    return `{${Object.entries(value).map(([key, item]) => {
      const name = key === '__proto__' ? `[${JSON.stringify(key)}]` : /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
      return `${name}: ${emit(item)}`;
    }).join(', ')}}`;
  }
  return '/* unsupported */ undefined';
}

/** Renders regression tests: bugs pin the old outcome; intended changes pin the new one. */
export function exportVitest(opts: { fnName: string; importPath: string; items: LabeledDivergence[] }): string {
  const { fnName, importPath, items } = opts;
  const tests = items.map(({ label, divergence }) => {
    const call = `${fnName}(${divergence.args.map(arg => literal(arg)).join(', ')})`;
    const title = JSON.stringify(`${label}: ${call}`);
    const outcome = label === 'bug' ? divergence.pair.old : divergence.pair.new;
    if (outcome.kind === 'timeout') return `  it.skip(${title}, () => {\n    // timed out\n  });`;
    const assertion = outcome.kind === 'throw'
      ? `expect(() => ${call}).toThrow(); // ${JSON.stringify(outcome.name)}`
      : `expect(${call}).toEqual(${literal(outcome.value)});`;
    return `  it(${title}, () => {\n    ${assertion}\n  });`;
  });
  if (!tests.length) tests.push("  it.todo('no labeled divergences');");
  return `// Generated by DiffWitness. Labels: bug = new must match old; intended = new behavior pinned.\nimport { describe, it, expect } from 'vitest';\nimport { ${fnName} } from ${quote(importPath)};\n\ndescribe(${quote(`${fnName} (DiffWitness)`)}, () => {\n${tests.join('\n\n')}\n});\n`;
}
